/**
 * 화면의 제목(h1) — **보이지 않는다**.
 *
 * 공개 화면 대부분은 제목 줄이 없다(사이드바가 지금 위치를 말한다). 그래서 문서에는
 * h1이 하나도 없었다 — 홈 · 뉴스 · 실적 · 실시간 차트 · 리포트(2026-09-26 외부 방문자
 * 점검, 성장 감시 「H1 없음」). 검색엔진은 h1을 그 문서가 무엇에 관한 것인지의 단서로
 * 쓰고, 화면 읽기 프로그램 사용자는 제목으로 화면을 건너다닌다.
 *
 * 눈에 보이는 제목 줄을 새로 넣는 것은 화면 설계를 바꾸는 일이라 여기서 하지 않는다.
 * 글자는 그 화면의 기본 메타 제목(`lib/page-meta-routes`)과 같게 둔다 — 화면이 스스로 말하는 것과
 * 다른 약속을 하지 않게.
 */
export function PageHeading({ children }: { children: string }) {
  return <h1 className="sr-only">{children}</h1>;
}
