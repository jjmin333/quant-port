"use client";

import { useCallback } from "react";
import { useRouter } from "next/navigation";
import { useAuth } from "@/components/providers/auth-provider";

/*
로그인이 필요한 동작의 **단일 규칙** (2026-09-04 사용자 요청 2).

# 무엇이 잘못돼 있었나

목표가 모달은 이 규칙을 이미 갖고 있었다 — 버튼에 「로그인하고 저장」이라고 적고,
누르면 저장 대신 로그인으로 보내면서 돌아올 자리를 `next`에 싣는다.

**나머지는 그러지 않았다.** 스탬프 생성·보유 종목 등록·관심 등록은 비로그인
상태에서도 평범한 버튼으로 보였고, 눌러서 폼을 다 채우고 저장하면 그때서야 401이
돌아왔다. 사용자가 보는 것은 「스탬프 저장에 실패했습니다」라는 문장 하나였고,
그 문장은 **왜 실패했는지도 무엇을 하면 되는지도** 말하지 않는다.

규칙을 훅 하나로 모으는 이유는 그 규칙이 세 조각이기 때문이다 — 버튼 문구, 눌렀을
때의 분기, 돌아올 자리. 화면마다 손으로 맞추면 셋 중 하나는 반드시 빠지고, 빠진
것은 **비로그인으로 그 화면을 열어 봐야만** 보인다.

# 막는 자리는 **둘 중 하나**다

이 훅에는 두 가지 쓰임이 있고, 그 둘은 목적이 다르다.

- **여는 버튼**(관심 추가, `/stamps`의 「스탬프 찍기」): `run()`으로 감싼다. 누르면
  창이 열리는 대신 로그인으로 간다. 창 밖에서는 로그인으로 가는 길이 화면에 남아
  있으므로, 여기서 잠그면 그 길까지 함께 잠긴다.
- **창 안의 저장 버튼**(스탬프·보유 등록·목표가): `authed`로 **비활성화**한다
  (2026-09-05 사용자 요청 4). 종목 상세의 셋은 이제 비로그인에게도 **창이 열리므로**,
  401이 날 요청을 막는 자리가 그 버튼 하나뿐이다. 죽은 버튼만 두면 다음에 할 일이
  화면에서 사라지므로, 로그인으로 가는 길은 버튼 아래 한 줄이 대신 연다
  (`components/auth/login-required-note`).

두 경우 모두 목적은 같다 — **401이 날 요청을 아예 보내지 않는 것**. 다른 것은 그
목적을 이루는 자리뿐이다.
*/

export type LoginGate = {
  /** 지금 로그인돼 있는가. 버튼 문구를 고르는 데 쓴다. */
  authed: boolean;
  /**
   * 저장 동작을 감싼다.
   *
   * 로그인돼 있으면 `action`을 그대로 부르고, 아니면 **부르지 않고** 로그인으로
   * 보낸다. 반환값이 false면 「보냈다」는 뜻이라 호출부는 거기서 멈추면 된다.
   */
  run: (action: () => void | Promise<void>) => boolean;
  /**
   * 버튼에 적을 말. 로그인돼 있으면 받은 그대로, 아니면 「로그인하고 …」.
   *
   * **로그인 전 문구는 버튼마다 달라야 한다.** 처음에는 셋 다 「로그인하고 저장」으로
   * 맞췄는데, 종목 헤더에 그 버튼이 셋 나란히 서서 **같은 글자 셋**이 됐다
   * (스탬프·보유 등록·목표가). 로그인이 필요하다는 것은 알겠지만 어느 것이 무엇인지
   * 사라진다 — 아이콘만 남는다. 그래서 훅을 만들 때 그 자리의 동사를 받는다.
   *
   * 창 **안의 저장 버튼도 마찬가지다** (2026-09-05 사용자 요청 1). 한동안은 창 안에서만은
   * 「로그인하고 저장」으로 뭉뚱그렸다 — 무엇을 저장하는지 창 제목이 이미 말한다고 봤다.
   * 그런데 창 셋을 오가며 보면 **버튼 글자가 셋 다 같다**: 스탬프 창에서도, 보유 등록
   * 창에서도, 목표가 창에서도 「로그인하고 저장」이다. 제목은 창을 열 때 한 번 읽고
   * 눈은 버튼으로 내려가므로, 그 자리에서 무엇을 하는지 말해야 하는 것은 버튼 쪽이다.
   * 지금은 셋이 **「스탬프」·「보유 등록」·「목표가 설정」**이다 — 종목 헤더에 선 세
   * 버튼의 이름과 같은 말이라, 창을 연 버튼과 창 안의 버튼이 같은 것을 가리킨다
   * (2026-09-05 사용자 요청 4에서 사용자가 지정한 문구).
   */
  label: (label: string) => string;
};

/**
 * @param verb 로그인 전 버튼에 붙일 말 — 「저장」이면 「로그인하고 저장」이 된다.
 *             버튼이 여럿 나란히 서는 자리에서는 그 자리의 동사를 넘긴다.
 */
export function useLoginGate(verb = "저장"): LoginGate {
  const router = useRouter();
  const { session } = useAuth();
  const authed = Boolean(session);

  const run = useCallback(
    (action: () => void | Promise<void>) => {
      if (!authed) {
        /*
          돌아올 자리는 **지금 주소 그대로**다(쿼리 포함). 목표가 모달이 쓰던 것과
          같은 형태라, 로그인 뒤 보던 종목의 화면으로 돌아온다.

          적어 둔 폼 값은 여기서 사라진다 — 그걸 살리려면 로그인 왕복을 넘겨 실어야
          하고, 그건 이 훅이 아니라 각 화면의 일이다.
        */
        router.push(
          `/login?next=${encodeURIComponent(window.location.pathname + window.location.search)}`,
        );
        return false;
      }
      void action();
      return true;
    },
    [authed, router],
  );

  const label = useCallback(
    (text: string) => (authed ? text : `로그인하고 ${verb}`),
    [authed, verb],
  );

  return { authed, run, label };
}
