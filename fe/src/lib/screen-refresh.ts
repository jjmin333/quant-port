/*
화면을 **열어 둔 채로도** 값이 늙지 않게 하는 주기.

# 어디서 시작했나

2026-09-16에 홈만 고쳤다(`lib/dashboard-refresh`). 홈의 카드들은 저마다
`useEffect`에서 한 번 받고 그대로 서 있었고, 가격만 스트림·폴링이 밀어 줘서
화면이 살아 있는 것처럼 보였다 — 정작 브리핑과 「실시간 뉴스」는 마운트 시각의
글이었다.

**같은 병이 나머지 화면 전부에 있었다** (2026-09-16 사용자 요청). 뉴스 목록도,
실적 일정도, AI 추천 랭킹도, 리포트 피드도 열어 둔 채로는 마운트 시각에 묶여
있었다. 그래서 이 파일은 홈의 것이 아니라 **앱 전체의 규칙**이고, 이름도
`dashboard-` 에서 `screen-` 으로 바꿨다.

# 왜 두 주기인가

블록마다 **뒤에서 값을 만드는 주기가 다르다.** 5분마다 다시 물어도 답이 같은
것을 5분마다 묻는 것은 회선과 DB만 쓰는 일이라(운영은 1 ECPU짜리 DB 하나다),
뒤에서 바뀌는 만큼만 묻는다. 「메뉴 중요도에 따라 둘 중 하나」라는 요청의
실질은 이것이다 — 자주 보는 화면이 아니라 **자주 바뀌는 값**이 빠른 쪽이다.

  - `NEWS_REFRESH_MS` (90초) — 뉴스 목록 화면. 여기만 따로인 이유는 그 상수의
    머리글에 있다.
  - `SCREEN_REFRESH_MS` (5분) — 장중에 뒤에서 값이 바뀌는 것: 시장 브리핑(배치가
    장중 30분·그 외 1시간), 뉴스 목록과 그 기사로 세는 키워드·언급 종목, 거래대금
    상위(서버 랭킹 스냅샷이 5분), 리포트 피드(사람이 아무 때나 쓴다).
  - `SCREEN_SLOW_REFRESH_MS` (30분) — 하루 한 번 도는 배치가 만드는 것: AI 추천
    랭킹, 실적 일정과 그 집계, 지수 점수 배지, 목표가 예측 판정. 이 값들이 바뀌는
    순간은 하루에 한 번뿐이라 5분 주기는 스물아홉 번이 헛걸음이다. 그래도 「열어 둔
    채 날짜가 바뀌면 반영된다」는 보장은 지켜야 해서 0이 아니다.

# 안 보이는 탭은 세지 않는다

전부 `useVisibleInterval`을 지난다 — 숨은 탭은 회차를 건너뛰고, 돌아오는 순간
마지막 호출로부터 한 주기가 지났으면 한 번 메운다. 창을 다섯 띄운 사용자에게
폴링은 다섯 배이고, 그 규칙을 한 곳에 모아 둔 이유가 그것이다(2026-09-15 요청 3).

# 실패는 화면을 비우지 않는다

첫 적재의 실패는 「없음」이지만 **갱신의 실패는 「아직 그것」**이다. 갱신 한 번이
실패했다고 보고 있던 기사·브리핑을 지우면, 낡은 값을 고치려던 일이 값을 통째로
없애는 일이 된다. 호출부마다 첫 적재와 갱신을 가른다.

# 갱신은 스피너를 띄우지 않는다

같은 이유로 **주기 갱신은 로딩 상태를 건드리지 않는다.** 5분마다 목록이 스켈레톤으로
한 번 지워졌다 돌아오면 고치려던 것보다 나쁘다 — 사용자는 자기가 뭘 잘못 눌렀다고
읽는다. 첫 적재만 스피너를 쓴다.
*/

/** 장중에 뒤에서 값이 바뀌는 블록의 갱신 주기. */
export const SCREEN_REFRESH_MS = 5 * 60_000;

/**
 * 뉴스 목록 화면만 쓰는 **빠른 주기** (2026-09-17 사용자 요청).
 *
 * 「최근 15분간 기사가 없는 줄 알았는데, 보고 있으니 3분 전~15분 전 기사가 한꺼번에
 * 뜬다」 — 절반은 수집 쪽이었고(서버의 검색어 회전을 생산성 차선으로 갈랐다),
 * 나머지 절반이 이 값이었다. 5분 주기는 수집이 아무리 빨라져도 **최대 5분을 더
 * 얹는다.** 실시간을 내건 화면에서 그 5분은 「안 들어온다」로 읽힌다.
 *
 * 90초인 이유는 위아래가 다 막혀 있어서다.
 *
 *   - 아래: 클라이언트 GET 캐시 30초와 집계 캐시 60초(`NEWS_AGGREGATE_TTL`)보다
 *     길어야 회차가 실제로 왕복한다. 짧으면 조용히 캐시로 떨어져 **고친 척만** 남는다
 *     (`screen-refresh.test.ts`가 이 관계를 잠근다).
 *   - 위: 서버 수집 틱이 2분이라 그보다 촘촘해도 새로 올 것이 없다.
 *
 * **뉴스 목록 화면에만 쓴다.** 홈은 카드가 열 장이고 가장 많이 열리는 화면이라
 * 5분 그대로다 — 운영 DB는 1 ECPU 하나다.
 */
export const NEWS_REFRESH_MS = 90_000;

/**
 * 하루 한 번 도는 배치가 만드는 블록의 갱신 주기.
 *
 * 실적 하이라이트의 클라이언트 캐시가 5분(`EARNINGS_TTL`)이라 이 값은 **그보다
 * 길어야** 실제로 왕복이 일어난다 — 캐시 TTL과 같은 값을 주면 시계가 몇 밀리초
 * 이르게 울린 회차가 조용히 캐시로 떨어진다.
 */
export const SCREEN_SLOW_REFRESH_MS = 30 * 60_000;
