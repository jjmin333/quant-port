/*
「다시 부를 때인가」 — **시계가 아니라 시각으로** 판정한다.

# 무엇이 잘못돼 있었나 (2026-09-16 사용자 지적 「탭을 계속 띄워놓고 있었는데 제대로
안 바뀌던데」)

`useVisibleInterval`은 「숨어 있는 동안 회차가 **울렸는가**」를 표식(`missed`)으로
들고 있다가, 다시 보일 때 울린 적이 있으면 한 번 메웠다. 그 전제는 **숨은 탭에서도
타이머가 돈다**는 것인데, 브라우저는 그러지 않는다.

  - 크롬은 5분 넘게 숨은 탭의 타이머를 **분당 한 번**으로 내리고(intensive
    throttling), 조건이 맞으면 탭을 아예 **얼린다**(freeze) — 얼린 탭에서는 콜백이
    하나도 돌지 않는다. 창이 다른 창에 **완전히 가려져도** 크롬은 그 탭을 `hidden`
    으로 본다.
  - 노트북을 덮으면 타이머는 멈춘 채 시각만 흐른다.

그래서 회차가 한 번도 안 울린 채 몇 시간이 지나는 일이 실제로 생기고, 그때 표식은
false다 — 돌아와도 「건너뛴 적 없음」으로 읽혀 **아무 일도 일어나지 않는다.** 같은
함정을 `lib/stream-awake`가 이미 한 번 밟았고, 거기 적어 둔 문장이 이것이다:
「울렸으니 지났다」는 믿을 수 없다.

# 그래서 무엇을 세는가

**마지막으로 부른 시각** 하나다. 회차가 울리든 말든, 보이게 되든, 창이 포커스를
받든, bfcache에서 되살아나든 — 물어보는 질문은 언제나 「마지막으로 부른 지 한 주기가
지났는가」다. 지났으면 부르고 시각을 갱신한다.

부수 효과로 **돌아올 때의 헛걸음도 준다.** 예전에는 30초 숨었다 돌아오기만 해도
회차가 울렸다면 한 번을 더 불렀는데, 값이 아직 한 주기보다 젊으면 부를 이유가 없다.
*/

/**
 * 타이머 지터·시계 해상도 때문에 **간발의 차로 놓치는 회차**를 막는 여유.
 *
 * `setInterval(fn, 30_000)`이 29,999ms에 울리는 일이 있는데, 엄격하게 재면 그 회차가
 * 통째로 미뤄져 주기가 사실상 두 배가 된다. 1초는 가장 짧은 주기(관심 목록 30초)에서도
 * 3%라 「너무 자주 부른다」 쪽으로 기울지 않는다.
 */
const DUE_TOLERANCE_MS = 1_000;

/**
 * 마지막 호출이 `lastRunAt`이었을 때, `now`에 다시 부를 때인가.
 *
 * @param ms 주기. 0 이하면 주기가 없다는 뜻이라 언제도 아니다.
 */
export function isRefreshDue(lastRunAt: number, now: number, ms: number): boolean {
  if (ms <= 0) return false;
  return now - lastRunAt >= ms - DUE_TOLERANCE_MS;
}
