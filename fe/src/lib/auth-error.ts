import { PortfolioFetchError } from "@/lib/api-client";

/**
 * `/auth/me` 가 실패했을 때 **로그아웃으로 취급해도 되는가.**
 *
 * # 왜 구분이 필요한가
 *
 * 「누구인지 물어봤는데 답을 못 받았다」와 「너는 로그인하지 않았다」는 다른 일이다.
 * 앞엣것은 서버가 잠깐 흔들린 것이고, 뒤엣것만 세션이 없다는 뜻이다. 그런데
 * `AuthProvider`는 둘을 같은 `catch`로 받아 **무조건 세션을 비웠다**.
 *
 * 그래서 429 한 번, 5xx 한 번, 지하철에서 끊긴 요청 한 번에 로그인한 사용자의
 * 헤더가 「로그인 / 회원가입」으로 바뀌고 화면에서 자기 데이터가 사라졌다.
 * 쿠키는 멀쩡히 살아 있으므로 **새로고침하면 돌아온다** — 사용자에게는 앱이
 * 제멋대로 로그아웃시킨 것으로만 보인다.
 *
 * 실측(2026-09-06): e2e 전체 실행 중 `/auth/*` 가 IP 레이트 리밋(30 req/s)에
 * 걸리자 로그인 직후 화면이 비로그인 헤더를 그렸다.
 *
 * # 같은 판단이 이미 한 군데 있다
 *
 * `session-fetch.ts` 의 `refreshSession` 은 **401·403일 때만** 「갱신 못 함」을
 * 굳히고 5xx·네트워크 실패는 굳히지 않는다 — "그때까지 로그인해 있던 사람이
 * 서버가 잠깐 흔들렸다고 로그아웃당하면 안 된다". 이 함수는 그 규칙을 세션
 * 상태에도 똑같이 적용한다.
 *
 * # 답을 모를 때는 세션을 유지한다
 *
 * 상태 코드가 없는 오류(네트워크 단절, JSON 파싱 실패)는 **서버가 아니라고 말한
 * 적이 없는** 경우다. 그대로 두고 다음 기회에 다시 묻는다. 잘못 유지해도 보호
 * 화면의 데이터는 서버가 401로 다시 막으므로, 여기서 낙관하는 비용은 헤더가 한
 * 박자 늦게 바뀌는 것뿐이다.
 */
export function isSignedOutError(err: unknown): boolean {
  if (err instanceof PortfolioFetchError) {
    return err.status === 401 || err.status === 403;
  }
  return false;
}
