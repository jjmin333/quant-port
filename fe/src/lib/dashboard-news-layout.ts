/**
 * 홈 첫 행의 배치 규칙 — **뉴스 카드가 브리핑과 한 행에 서는가.**
 *
 * # 왜 함수로 빼는가 (2026-09-05 사용자 요청 1)
 *
 * PC에서 실시간 뉴스가 **다섯 줄만** 보이는 날이 있었다. 캐시가 아니라 배치였다:
 * 뉴스 칸은 브리핑의 높이를 채우려고 `lg:relative` 안에 카드를 `lg:absolute`로
 * 띄우는데, **절대 배치된 자식은 부모의 높이를 만들지 못한다.** 그래서 브리핑이
 * 아직 생성되지 않은 시각에는 옆에 설 카드가 없어 칸이 바닥값(`lg:min-h-[22rem]`)
 * 그대로 352px에 멈췄고, 카드는 열넷을 담은 채 **다섯 줄만 보이고 나머지는 안에서
 * 스크롤**됐다(실측 1440px: 칸 352px · 보이는 줄 5).
 *
 * 「전폭으로 늘어난다」는 그리드 쪽에만 적혀 있었고 — `grid-cols-1`로 바꾸는 분기는
 * 있었다 — **칸과 카드의 클래스는 그 분기를 몰랐다.** 같은 판단이 세 자리에
 * 흩어져 있으면 그중 하나는 반드시 빠진다. 그래서 판단을 여기 한 번만 적고 셋이
 * 그것을 읽는다.
 */

export type BriefingRowState = {
  /** 브리핑을 아직 받는 중인가. 받는 중에는 자리를 비워 두지 않는다 — 곧 설 카드다. */
  loading: boolean;
  hasDomestic: boolean;
  hasUs: boolean;
};

/**
 * 뉴스 카드가 브리핑과 **한 행을 나눠 쓰는가**.
 *
 * `true`면 뉴스 칸은 행 높이 계산에서 빠지고(절대 배치) 넘치는 기사는 카드 안에서
 * 스크롤된다. `false`면 뉴스가 그 행을 혼자 쓰므로 **자연 높이 그대로** 둔다 —
 * 맞출 상대가 없는데 높이를 352px로 묶으면 전폭으로 늘어난 카드 안에서 다시
 * 스크롤하게 된다.
 */
export function newsCardSharesBriefingRow(state: BriefingRowState): boolean {
  return state.loading || state.hasDomestic || state.hasUs;
}
