/*
가격이 갱신되는 박자. **화면 하나가 아니라 앱 전체의 것이다.**

# 왜 상수 하나인가

2026-09-04 이전에는 화면마다 자기 숫자를 들고 있었다:

	실시간 차트·종목 상세   2초   use-quote-detail.ts
	형성봉                  2초   use-quote-candles.ts
	마켓 랭킹 가격          1초   market-radar-config.ts
	보유·관심 목록          5초   holdings-page-client / watchlist-client
	AI 랭킹                 없음  (한 번 받고 끝)

같은 종목의 같은 가격인데 어느 화면에서 보느냐에 따라 최대 5초까지 늙어 있었고,
사용자에게는 그것이 **한 앱이 종목마다 다른 값을 말하는 것**으로 보인다. 실제로
09-04에 그 지적이 있었다(랭킹 5,200원 vs 상세 5,100원 — 원인은 달랐지만 증상은
「화면마다 다른 가격」으로 똑같았다).

이제 숫자는 여기 하나뿐이고 나머지는 전부 import한다. 상수가 흩어져 있으면 다음에
누군가 한 곳만 고치고, 그 사실은 **아무 데서도 안 터진다**.

# 왜 1초인가

서버가 새 값을 만드는 주기다 — `be/internal/service/market_poller.go`의
`marketPricePollInterval`. 그보다 자주 물으면 방금 받은 값을 다시 받고, 그보다
늦추면 서버가 만든 값을 놓친다. 두 상수는 언제나 같이 움직여야 한다.

2026-09-04 오전에 2초로 모았다가 같은 날 오후에 1초로 내렸다(사용자 요청 5).
**되돌린 게 아니라 그 사이에 조건이 달라졌다** — 2초를 고른 근거는 「폴링이
1초로 만든 값의 절반을 아무도 안 읽는다」였는데, 가격이 SSE로 옮겨 가면서
만든 값이 만드는 즉시 구독자에게 밀려 나가 **전부 읽히게** 됐다. 상류 실측이
median 999ms이므로 1초가 그 박자와 정확히 맞는다. 자세한 근거는 위 Go 상수의
머리글에 있다.

# 폴링은 보조 경로다

값이 실제로 흐르는 길은 `useQuoteStream`(다심볼 SSE)이다 — 서버가 한 번 만든
값을 모든 뷰어에게 나눠 주므로 서버 작업이 뷰어 수와 무관하다. 폴링은 스트림이
아직 안 붙었거나 끊긴 동안의 **받침대**이고, 스트림이 살아 있는 동안에는 훅이
스스로 폴링을 멈춘다.
*/
export const PRICE_POLL_MS = 1_000;

/*
스트림이 붙어 있는 동안의 폴링 주기.

0이 아니라 **느린 박자**인 이유: SSE가 조용한 것과 「가격이 안 변한 것」은 화면에서
구분되지 않는다. 프록시가 연결을 조용히 끊거나 서버가 발행을 멈춰도 EventSource는
한동안 `open`으로 남아 있을 수 있고, 그때 폴링까지 0이면 화면이 **낡은 값을 든 채
아무 일도 없는 것처럼** 서 있는다.

30초는 사람이 「멈췄다」고 느끼기 전에 한 번은 실제 값을 확인하게 하면서, 요청
수로는 2초 폴링의 15분의 1이다.
*/
export const PRICE_POLL_MS_WHILE_STREAMING = 30_000;
