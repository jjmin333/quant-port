package service

import (
	"strings"
)

/*
기사 본문의 **통칭·별명**을 종목으로 푼다.

# 무엇이 잘못돼 있었나 (2026-09-04 사용자 지적 10)

「37% 빠진 **삼전닉스**…노무라 "심각한 저평가"」 기사에 종목이 하나도 안 붙었다.
삼성전자와 SK하이닉스 둘 다에 대한 기사인데도.

이름 인덱스는 **상장명**으로 만든다. 그 표에 「삼성전자」와 「SK하이닉스」는 있지만
「삼전닉스」는 없고, 있을 수도 없다 — 그건 회사가 등록한 이름이 아니라 시장이
두 종목을 묶어 부르는 말이다. 기존 별칭 표(`HangulNameAliases`)로도 못 푼다.
그쪽은 **읽기 하나 → 종목 하나**이고(「네이버」→ NAVER), 여기 필요한 것은
**한 단어 → 종목 여럿**이다.

# 왜 별도 표인가

기존 별칭 표는 「영문 상장명의 한글 읽기」다 — KT를 「케이티」로 적은 것뿐이라
회사가 바뀌지 않는 한 안 바뀌고, 틀릴 여지도 거의 없다.

이 표는 성격이 다르다. **시장이 지어낸 말**이라 유행을 타고, 새것이 계속 생기고,
때로는 뜻이 갈린다. 둘을 한 표에 섞으면 「읽기」와 「별명」의 판정 기준이 하나로
묶여서, 별명 하나를 넣으려고 읽기 규칙을 흔들게 된다.

# 정밀도 규칙은 그대로다

`news_symbol_match.go` 머리글의 「정밀도가 재현율보다 중요하다」가 여기도 적용된다.
그래서 표에 넣는 기준을 좁게 잡는다:

 1. **세 글자 이상.** 짧은 별명은 일상어와 부딪힌다.
 2. **그 말이 종목을 가리킬 때만 쓰이는 말.** 「삼전닉스」는 다른 뜻이 없다.
    반대로 「대장주」·「이차전지」 같은 범주어는 넣지 않는다 — 어느 종목인지
    기사마다 달라서 표로 굳힐 수 없다.
 3. **상장명으로 되짚어 푼다.** 심볼을 직접 적지 않는다. 종목코드를 손으로 적으면
    상장폐지·코드 변경 때 조용히 틀린 종목을 가리키게 되고, 그건 아무 데서도
    안 터진다. 이름으로 적어 두면 인덱스에 그 이름이 없어질 때 **그냥 안 붙는다.**
 4. **경계 검사를 거친다.** 매칭은 `nameTokenMatch`가 하므로 「삼전닉스」가 더 긴
    단어의 꼬리로 걸리지 않는다.
*/

/*
domesticNicknames — 별명 → 그 말이 가리키는 **상장명들**.

키는 소문자. 값은 이름 인덱스에서 찾을 상장명이고, 그중 인덱스에 있는 것만 붙는다.

「삼전」·「하이닉스」를 따로 두는 이유: 이 둘은 기사 제목에서 단독으로도 흔히 쓰인다
(「삼전 7만원 회복」). 상장명은 각각 「삼성전자」·「SK하이닉스」라 그대로는 안 걸린다 —
후자는 인덱스 키가 「sk하이닉스」여서 앞 경계 검사에 막힌다.
*/
var domesticNicknames = map[string][]string{
	// 반도체 두 종목을 묶어 부르는 말. 2026-09-04 사용자 지적의 그 기사다.
	"삼전닉스": {"삼성전자", "SK하이닉스"},
	"삼성닉스": {"삼성전자", "SK하이닉스"},
	"삼전":   {"삼성전자"},
	"하이닉스": {"SK하이닉스"},
	"에스케이하이닉스": {"SK하이닉스"},

	// 지주·계열 통칭. 상장명이 영문이라 한글 표기로는 안 걸리는 것들이다.
	"현차":   {"현대차"},
	"기아차":  {"기아"},
	"엘지엔솔": {"LG에너지솔루션"},
	"엘지엔에스": {"LG에너지솔루션"},
	"엘지화학": {"LG화학"},
	"에스디아이": {"삼성SDI"},
	"삼바":   {"삼성바이오로직스"},
	"셀트리온제약": {"셀트리온제약"},
	"네이버웹툰": {"NAVER"},
	"카뱅":   {"카카오뱅크"},
	"카페이":  {"카카오페이"},
	"두산에너": {"두산에너빌리티"},
	"한전":   {"한국전력"},
	"포스코홀딩스": {"POSCO홀딩스"},
	"현대건기": {"HD현대건설기계"},
}

/*
nicknameMinRunes — 이보다 짧은 별명은 표에 있어도 쓰지 않는다.

표를 사람이 손으로 채우므로, 두 글자짜리를 무심코 넣었을 때 **코드가 막아 준다.**
「삼전」이 딱 두 글자라 이 문턱을 3으로 두면 빠지는데, 그건 넣고 싶은 항목이다 —
그래서 2로 두고 대신 표 쪽 주석에 「그 말이 종목을 가리킬 때만 쓰이는 말」을
못박아 두었다. 한 글자는 어떤 경우에도 안 된다.
*/
const nicknameMinRunes = 2

/*
matchNicknameSymbols — 본문에서 별명을 찾아 심볼을 낸다.

`idx`는 `rebuildNameIndex`가 만든 **상장명 → 심볼** 표다. 별명이 가리키는 이름 중
그 표에 있는 것만 붙으므로, 상장폐지나 이름 변경이 나면 조용히 안 붙게 된다
(틀린 종목을 붙이는 것보다 낫다).

`textLower`는 이미 소문자여야 한다 — 호출부(`extractSymbols`)가 한 번만 낮춘다.
*/
func matchNicknameSymbols(textLower string, idx map[string]string) []string {
	if textLower == "" || len(idx) == 0 {
		return nil
	}
	var out []string
	seen := map[string]struct{}{}
	for nickname, names := range domesticNicknames {
		if len([]rune(nickname)) < nicknameMinRunes {
			continue
		}
		/*
			상장명이 그 별명과 **같으면 건너뛴다.** 이름 인덱스가 이미 그 말을
			직접 맞추므로 여기서 또 볼 이유가 없고, 무엇보다 이 경로는
			`domesticNameNeedsCode`(두 글자·일상어 이름은 종목코드를 요구한다)를
			지나지 않는다 — 별명으로 그 규칙을 우회시키면 안 된다.
		*/
		if _, isListedName := idx[nickname]; isListedName {
			continue
		}
		if !nameTokenMatch(textLower, nickname) {
			continue
		}
		for _, name := range names {
			sym, ok := idx[strings.ToLower(strings.TrimSpace(name))]
			if !ok || sym == "" {
				continue
			}
			if _, dup := seen[sym]; dup {
				continue
			}
			seen[sym] = struct{}{}
			out = append(out, sym)
		}
	}
	return out
}
