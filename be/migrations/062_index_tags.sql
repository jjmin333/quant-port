--
-- 홈 스트립은 지수마다 「AI 56」을 달고 있었다. 그 점수는 횡단면 랭킹이 아니라
-- 절대 지표로 만든 값이라 코스피 56과 나스닥 62를 비교할 수 없는데, 나란히 놓이면
-- 사용자는 반드시 비교한다. 게다가 규칙 기반 값에 「AI」가 붙어 있어 무엇을 보고
-- 나온 수인지 되짚을 수도 없었다.
--
-- 대신 **관측 가능한 사실**을 코드로 적어 둔다: `high_52w`, `streak_up:4`,
-- `sma20_recover` 처럼. 숫자가 붙는 키워드는 `코드:값` 꼴이고, 화면에 나갈 문구는
-- FE가 매핑한다 — 문구를 고치자고 배치를 다시 돌릴 이유는 없다.
--
-- 점수 컬럼과 같은 배치가 같은 행에 쓰므로 별도 표를 만들지 않는다.
-- 쉼표로 잇고, 코드 8개까지 들어가도 255를 넘지 않는다.

ALTER TABLE index_daily_closes
  ADD COLUMN tags VARCHAR(255) NOT NULL DEFAULT '' AFTER ai_summary;
