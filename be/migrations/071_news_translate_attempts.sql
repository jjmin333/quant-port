-- 해외 제목 번역 재시도 횟수 (2026-09-14 사용자 요청 3)
--
-- # 왜 필요한가
--
-- `ListMissingTranslation` 은 `headline_ko` 가 빈 행을 published_at 역순으로 24건
-- 집어 2분마다 다시 시도한다 성공하면 그 행은 집합에서 빠지므로 보통은 흘러간다
--
-- 문제는 **영원히 실패하는 행**이다 2026-09-13~14 실측에서 자리표시자 되돌리기가
-- Azure 응답에 대해 항상 실패해(`$QPZ0` → `$QPZ 0`) 같은 24건이 하루에 720번
-- 다시 나갔다 하루 12,559 요청 · 1,069,514자 그날 새 기사는 511건뿐이었다
--
-- 자리표시자는 고쳤지만(names.go) **고친 것은 원인 하나**다 다음 실패가 무엇이든
-- 같은 모양으로 돌아온다 — 조용히, 청구서에만 보이게 그래서 원인이 아니라 **구조**에
-- 상한을 둔다 세 번 실패한 제목은 영어로 남긴다
--
-- # 왜 3인가
--
-- 번역 실패의 대부분은 그 제목 자체의 성질이다(고유명사 덩어리 · 숫자만 있는 제목)
-- 일시적인 장애는 한 번의 재시도로 거의 다 걷힌다 세 번은 그 둘 사이이고, 3회에서
-- 멈추면 최악의 낭비가 제목당 3회로 묶인다
--
-- # 다시 시도하려면
--
-- UPDATE news_articles SET translate_attempts = 0 WHERE market = 'us' AND ...
-- 번역기를 바꾸거나 규칙을 고친 뒤 소급하려면 이 한 줄이다

ALTER TABLE news_articles
  ADD COLUMN translate_attempts TINYINT UNSIGNED NOT NULL DEFAULT 0;
