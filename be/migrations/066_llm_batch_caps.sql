-- AI 요약 배치의 하루 상한을 250 → 350으로, 토큰 예비분을 120K → 200K로 올린다.
--
-- # 왜 지금 올리나
--
-- 250은 「호출 500의 절반쯤」이 아니라 **토큰에서 나온 숫자**였다. 실측
-- (2026-09-08, Redis 배치 이력)으로 한 호출이 실제 청구하는 토큰은 국내 2,258 ·
-- 해외 1,939이고, 뉴스 브리핑이 하루 국내 약 140K · 해외 약 80K를 따로 쓴다.
-- 그래서 산술 천장은 국내 381건 · 해외 474건이고, 20% 여유를 남긴 값이 350이다.
--
-- 상한을 올린다고 그만큼 쓰는 것은 아니다. 실사용을 정하는 것은 상한이 아니라
-- **후보 수**이고, 상한 250이던 동안에도 레이더 후보가 먼저 말라 실제로는 국내
-- 106 · 해외 135건만 돌았다. 이 인상은 같은 날 들어가는 대상 선정 3층
-- (실시간 차트 · AI 랭킹 회전 · 보유/관심 미분석)이 만들어 내는 후보를 받아
-- 주기 위한 것이다.
--
-- # 예비분을 함께 올리는 이유
--
-- 진짜 안전판은 상한이 아니라 예비분이다. 배치가 끝난 뒤에도 자정까지 브리핑이
-- 돌고 관리자 수동 생성이 끼어들 수 있어서, 배치가 그 몫까지 먹으면 그날 남은
-- 시간 동안 브리핑이 굶는다. 350건이 최대치로 돌 때를 가정해 200K를 남긴다.
--
-- # 한 번만 적용된다
--
-- 값 갱신은 관리자가 손대지 않은 행에만 걸어야 한다. 가드는 행이 아니라 **컬럼의
-- DEFAULT**를 본다(MigrateLLMBatchCapsIfNeeded) — DEFAULT가 350이 되면 다시
-- 돌지 않으므로, 나중에 관리자가 250으로 되돌려도 재기동이 그 선택을 덮지 않는다.
--
-- NOTE: 주석 안에 문장 종결 기호를 넣지 않는다. splitSQLStatements가 파싱 없이
-- 그 문자로 파일을 자르기 때문에, 주석 속 한 글자가 statement를 반으로 쪼갠다.

ALTER TABLE llm_settings
  ALTER COLUMN daily_cap SET DEFAULT 350;

ALTER TABLE llm_settings
  ALTER COLUMN token_reserve SET DEFAULT 200000;

UPDATE llm_settings SET daily_cap = 350 WHERE id = 1 AND daily_cap = 250;

UPDATE llm_settings SET token_reserve = 200000 WHERE id = 1 AND token_reserve = 120000;
