-- 일별 종가 행에 「핵심 요약 한 문단」을 함께 쌓는다 (2026-09-15 사용자 요청 1)
--
-- # 왜 컬럼이 하나 더 필요한가
--
-- `ai_summary`에는 LLM이 쓴 **네 갈래 본문을 통째로 이어붙인 글**이 들어 있다
-- (밸류에이션·기술적·내부자·뉴스 — `dailyCloseSummaryText`) 같은 호출이 그와 별개로
-- `overview` 한 문단을 쓰는데, 그것은 네 갈래 **전체를 근거로 다시 쓴 요약**이지
-- 본문의 앞부분이 아니다
--
-- 종목 모달의 「간단」은 지금까지 `ai_summary`의 앞 두 문장을 잘라 썼다 자르는 것과
-- 요약하는 것은 다른 일이라, 앞 두 문장이 하필 밸류에이션 이야기만 하면 「간단」이
-- 네 갈래 중 한 갈래만 말하게 된다 — 개요 탭이 2026-09-03에 고친 것과 같은 실패다
--
-- # 왜 여기에 쌓는가
--
-- `overview`가 사는 곳은 Redis 캐시(24시간)와 `stock_summary_narratives`(종목당 한 벌,
-- 최신만)다 둘 다 **그날의 글**을 남기지 않는다 모달은 「9-15 기준」이라고 날짜를
-- 적어 놓고 글을 보여 주므로, 날짜와 글이 같은 행에 있어야 그 말이 참이 된다
--
-- 과거 행은 채우지 않는다 그날의 원문이 이미 없어 소급할 자리가 없다 비어 있는
-- 행에서는 화면이 예전처럼 `ai_summary`의 앞 두 문장으로 되돌아간다
--
-- DEFAULT ('') 인 이유는 031_index_scores.sql 과 같다 — 종가 upsert 는 이 컬럼을
-- 적지 않으므로 기본값이 없으면 STRICT 모드에서 INSERT 가 통째로 거절된다

ALTER TABLE stock_daily_closes
  ADD COLUMN ai_overview TEXT NOT NULL DEFAULT ('') AFTER ai_summary;
