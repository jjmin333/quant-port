-- 60분봉 계층 제거 (2026-08-24)
--
-- # 왜 지우나
--
-- 60분봉은 인터벌 중 **혼자 압도적으로 비쌌다.** `candleFetchCount`가
-- `120 × 분`이라 첫 화면 한 번에 필요한 원본 1분봉이 이렇게 갈렸다:
--
--   1m=200봉(1호출) · 5m=600(3) · 10m=1,200(6) · 30m=3,600(18) · 60m=7,200(36) · 1d=200(1)
--
-- Toss `/candles`는 200봉/호출이고 `MARKET_DATA_CHART` 그룹을 **사용자가 차트를
-- 처음 열 때 쓰는 경로와 공유**한다. 즉 60분봉을 여는 행위가 다른 사람의 차트를
-- 밀어냈다. 실측(2026-08-23) 30분간 `/candles` rate-limit exceeded 343건.
--
-- # 부수 효과가 더 크다
--
-- `maxIntradayRawBars`가 「가장 굵은 인트라데이 간격 × 표시 봉 수」였다
-- (`120 × 60 = 7,200`). 60분봉이 빠지면 30분봉이 가장 굵어 `120 × 30 = 3,600`이
-- 된다. 그런데 이 상수는 **콜드 미스 경로의 페치 크기**이기도 해서
-- (`intraday1mFetchTarget`이 저장된 봉이 없으면 그대로 요청한다),
-- **콜드 미스 1회가 37호출 → 19호출로 거의 절반**이 된다.
-- 60분봉을 보든 안 보든 모든 인트라데이 첫 열람에 적용된다.
--
-- # 보관 기간은 그대로 60일이다
--
-- 계층 사다리에서 60m이 빠지면서 30m이 마지막 계층이 됐다. 롤업의 만료는
-- `intradayTierMaxAgeDays`가 아니라 **마지막 계층 자신의 ageDays**를 읽으므로
-- (`candle_rollup.go`의 「마지막 계층 만료」 블록), 30m의 ageDays를 30 → 60으로
-- 올려 총 보관 기간을 유지했다.
--
--   1m ──3일──▶ 5m ──7일──▶ 10m ──14일──▶ 30m ──60일──▶ 삭제
--
-- 30~60일 구간이 60분봉 대신 30분봉으로 남아 행 수는 약 2배가 되지만
-- (추정 +40MB), 그 구간의 **해상도는 오히려 좋아진다.**
--
-- # DELETE가 아니라 DROP PARTITION인 이유
--
-- DELETE는 행마다 redo/undo를 쌓는데 이 배포 대상의 스토리지 처리량이
-- **29 MiB/s**다. DROP PARTITION은 파일 단위라 거의 즉시 끝난다.
--
-- # 되돌릴 수 없다
--
-- 그래도 안전한 것은 60분봉이 **파생 데이터**이기 때문이다 — 원본은 1분봉과
-- 1일봉이고 60분봉은 롤업이 그것을 접어 만든 것이었다. 남은 계층과 영구 저장인
-- 1d는 그대로다.
--
-- 드롭 뒤에는 `'60m'`을 받아 줄 파티션이 없어 그 값의 INSERT가 **에러**가 된다.
-- 조용히 다른 곳에 들어가는 것보다 낫다 — 코드에서 `Interval60m`을 지웠으므로
-- 그런 쓰기가 남아 있다면 그것이 버그다.
--
-- 기존 설치는 `repository.DropCandleBars60mPartitionIfNeeded`가 가드와 함께
-- 같은 일을 한다. 두 정의는 같아야 한다.

ALTER TABLE candle_bars DROP PARTITION p_60m;
